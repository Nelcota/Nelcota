//! Caddy: one site per project, generated from the registry. On Docker hosts
//! it is a shared container; on systemd hosts, the distribution's service.

use std::{collections::BTreeSet, fs, process::Command};

use anyhow::{Context, bail};

use crate::{
    host::{Host, Manifest, Runtime},
    native,
    project::compose_command,
    util::ok,
};

/// Docker network that connects Caddy to the projects' apps.
pub const NETWORK: &str = "nelcota_edge";

const COMPOSE: &str = include_str!("../../../deploy/caddy-compose.yml");

/// Caddyfile with one block per project.
#[cfg(test)]
fn render(manifest: &Manifest) -> String {
    render_paused(manifest, &BTreeSet::new())
}

fn render_paused(manifest: &Manifest, paused: &BTreeSet<String>) -> String {
    let mut out = String::from(
        "# Generated by nelcota from nelcota-host.json. Do not edit by hand:\n\
         # use `nelcota init` / `nelcota remove`.\n",
    );
    for project in &manifest.projects {
        let upstream = match manifest.runtime {
            Runtime::Docker => format!("app-{}:8000", project.name),
            Runtime::Systemd => native::APP_LISTEN.to_owned(),
        };
        let tls = match manifest.local {
            true => "\ttls internal\n",
            false => "",
        };
        if paused.contains(&project.name) {
            out.push_str(&format!(
                "\n{domain} {{\n{tls}\theader Retry-After 60\n\trespond \"Project temporarily unavailable\" 503\n}}\n",
                domain = project.domain,
            ));
            continue;
        }
        out.push_str(&format!(
            // Files under /storage go byte for byte (ranges, ETags): not compressed.
            "\n{domain} {{\n{tls}\t@compressible not path /storage/*\n\
             \tencode @compressible zstd gzip\n\treverse_proxy {upstream}\n\theader {{\n\
             \t\t-Server\n\t\tStrict-Transport-Security \"max-age=31536000\"\n\
             \t\tX-Content-Type-Options \"nosniff\"\n\t}}\n}}\n",
            domain = project.domain,
        ));
    }
    out
}

/// Writes the Caddyfile (and, on Docker, Caddy's compose if it does not exist yet).
pub fn write(host: &Host, manifest: &Manifest) -> anyhow::Result<()> {
    let paused = manifest
        .projects
        .iter()
        .filter(|project| {
            host.project_dir(&project.name)
                .join(crate::maintenance::MARKER)
                .is_file()
        })
        .map(|project| project.name.clone())
        .collect();
    let mut content = render_paused(manifest, &paused);
    if let Some(config) = crate::updates::descriptor(host.root())? {
        let domain = config
            .origin
            .strip_prefix("https://")
            .context("invalid controller origin")?;
        content.push_str(&format!("\n{domain} {{\n\treverse_proxy unix//run/nelcota-updates-http/http.sock\n\theader Strict-Transport-Security \"max-age=31536000\"\n}}\n"));
    }
    if manifest.runtime == Runtime::Systemd {
        return write_native(&content);
    }
    let dir = host.caddy_dir();
    fs::create_dir_all(dir.join("config"))?;
    let compose = dir.join("docker-compose.yml");
    if !compose.is_file() {
        fs::write(&compose, COMPOSE)?;
    }
    // Atomic swap inside the mounted folder (a single-file bind would not see the rename).
    let tmp = dir.join("config").join("Caddyfile.tmp");
    fs::write(&tmp, content)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(&tmp, fs::Permissions::from_mode(0o644))?;
    }
    fs::File::open(&tmp)?.sync_all()?;
    fs::rename(&tmp, dir.join("config").join("Caddyfile"))?;
    fs::File::open(dir.join("config"))?.sync_all()?;
    Ok(())
}

pub fn ensure_network() -> anyhow::Result<()> {
    let exists = Command::new("docker")
        .args(["network", "inspect", NETWORK])
        .output()
        .context("Docker not found")?
        .status
        .success();
    if !exists {
        let status = Command::new("docker")
            .args(["network", "create", NETWORK])
            .status()?;
        if !status.success() {
            bail!("could not create the {NETWORK} network");
        }
    }
    Ok(())
}

pub(crate) fn running(host: &Host) -> bool {
    compose_command(&host.caddy_dir())
        .args(["ps", "-q", "caddy"])
        .output()
        .map(|o| !String::from_utf8_lossy(&o.stdout).trim().is_empty())
        .unwrap_or(false)
}

/// Starts Caddy (or reloads the configuration if it is already up).
pub fn up(host: &Host, runtime: Runtime) -> anyhow::Result<()> {
    if runtime == Runtime::Systemd {
        native::systemctl(&["enable".into(), "--now".into(), "caddy".into()])?;
        return reload(host, runtime);
    }
    if running(host) {
        return reload(host, runtime);
    }
    let status = compose_command(&host.caddy_dir())
        .args(["up", "-d"])
        .status()?;
    if !status.success() {
        bail!("could not start Caddy");
    }
    ok("caddy up");
    Ok(())
}

/// Applies the new Caddyfile without dropping connections (if Caddy is up).
pub fn reload(host: &Host, runtime: Runtime) -> anyhow::Result<()> {
    if runtime == Runtime::Systemd {
        if native::unit_state("caddy").as_deref() == Some("active") {
            native::systemctl(&["reload".into(), "caddy".into()])?;
            ok("caddy reloaded");
        }
        return Ok(());
    }
    if !running(host) {
        return Ok(());
    }
    let status = compose_command(&host.caddy_dir())
        .args([
            "exec",
            "-T",
            "caddy",
            "caddy",
            "reload",
            "--config",
            "/etc/caddy/Caddyfile",
            "--adapter",
            "caddyfile",
        ])
        .status()?;
    if !status.success() {
        bail!("Caddy rejected the new configuration (see `docker logs nelcota-edge-caddy-1`)");
    }
    ok("caddy reloaded");
    Ok(())
}

/// The shared proxy's logs (certificates, routing errors).
pub fn logs(host: &Host, runtime: Runtime, follow: bool) -> anyhow::Result<()> {
    let mut command = match runtime {
        Runtime::Docker => {
            let mut command = compose_command(&host.caddy_dir());
            command.args(["logs", "--tail", "200"]);
            command
        }
        Runtime::Systemd => {
            let mut command = Command::new("journalctl");
            command.args(["--no-pager", "-n", "200", "-u", "caddy"]);
            command
        }
    };
    if follow {
        command.arg("-f");
    }
    if runtime == Runtime::Docker {
        command.arg("caddy");
    }
    crate::project::run(&mut command, "caddy logs")
}

pub fn down(host: &Host, runtime: Runtime, volumes: bool) -> anyhow::Result<()> {
    if runtime == Runtime::Systemd {
        return native::systemctl(&["stop".into(), "caddy".into()]);
    }
    let mut args = vec!["down"];
    if volumes {
        args.push("--volumes");
    }
    crate::project::run(
        compose_command(&host.caddy_dir()).args(&args),
        "caddy shutdown",
    )
}

/// Writes the Caddyfile atomically.
fn write_native(content: &str) -> anyhow::Result<()> {
    let path = std::path::Path::new("/etc/caddy/Caddyfile");
    let tmp = path.with_extension("nelcota-tmp");
    fs::write(&tmp, content)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(&tmp, fs::Permissions::from_mode(0o644))?;
    }
    fs::File::open(&tmp)?.sync_all()?;
    fs::rename(&tmp, path)?;
    fs::File::open("/etc/caddy")?.sync_all()?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::host::{PanelLogin, ProjectEntry};

    fn manifest(local: bool) -> Manifest {
        Manifest {
            version: 1,
            panel_login: PanelLogin::Shared,
            base_domain: None,
            local,
            runtime: crate::host::Runtime::Docker,
            image: "nelcota".into(),
            projects: vec![
                ProjectEntry {
                    name: "shop".into(),
                    domain: "api.shop.com".into(),
                },
                ProjectEntry {
                    name: "blog".into(),
                    domain: "blog.example.com".into(),
                },
            ],
        }
    }

    #[test]
    fn one_site_per_project() {
        let caddyfile = render(&manifest(false));
        assert!(caddyfile.contains(
            "api.shop.com {\n\t@compressible not path /storage/*\n\
             \tencode @compressible zstd gzip\n\treverse_proxy app-shop:8000"
        ));
        assert!(caddyfile.contains("blog.example.com {"));
        assert!(caddyfile.contains("reverse_proxy app-blog:8000"));
        assert!(!caddyfile.contains("tls internal"));
        assert!(render(&manifest(true)).contains("api.shop.com {\n\ttls internal\n"));
    }

    #[test]
    fn maintenance_blocks_only_the_selected_project() {
        let caddyfile = render_paused(&manifest(true), &BTreeSet::from(["shop".into()]));
        assert!(caddyfile.contains("api.shop.com {\n\ttls internal\n\theader Retry-After 60"));
        assert!(caddyfile.contains("respond \"Project temporarily unavailable\" 503"));
        assert!(!caddyfile.contains("reverse_proxy app-shop:8000"));
        assert!(caddyfile.contains("reverse_proxy app-blog:8000"));
    }
}
