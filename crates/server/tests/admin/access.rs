#[tokio::test]
async fn bucket_access_rules_from_templates() {
    let app = TestApp::spawn().await;
    let cookie = login(&app).await;
    for id in ["avatars", "docs"] {
        let created = send(
            &app,
            Method::POST,
            "/admin/api/storage/buckets",
            &cookie,
            json!({ "id": id }),
        )
        .await;
        assert_eq!(created.status, StatusCode::CREATED, "{}", created.text);
    }
    assert_eq!(
        access(&app, &cookie, "avatars").await["policies"],
        json!([])
    );

    let (ana, ana_token) = signed_up(&app, "ana@example.com").await;
    assert_ne!(
        upload(&app, &ana_token, &format!("avatars/{ana}/me.txt"))
            .await
            .as_u16()
            / 100,
        2
    );

    // Preview first: the SQL, nothing applied.
    let preview = send(
        &app,
        Method::POST,
        "/admin/api/storage/buckets/avatars/access",
        &cookie,
        json!({ "template": "own_folder", "preview": true }),
    )
    .await;
    assert_eq!(preview.status, StatusCode::OK, "{}", preview.text);
    assert_eq!(preview.body["applied"], false);
    assert!(
        preview.body["sql"][0]
            .as_str()
            .unwrap()
            .contains("storage.foldername(name)")
    );

    let created = send(
        &app,
        Method::POST,
        "/admin/api/storage/buckets/avatars/access",
        &cookie,
        json!({ "template": "own_folder" }),
    )
    .await;
    assert_eq!(created.status, StatusCode::OK, "{}", created.text);
    let rules = access(&app, &cookie, "avatars").await;
    assert_eq!(rules["public"], false);
    let policy = &rules["policies"][0];
    assert_eq!(policy["name"], "avatars_own_folder");
    assert_eq!(policy["command"], "ALL");
    assert_eq!(policy["all_buckets"], false);
    // Postgres prints the expression back with casts; the panel reads this form.
    let using = policy["using"].as_str().unwrap();
    assert!(using.contains("bucket_id = 'avatars'::text"), "{using}");
    assert!(using.contains("storage.foldername(name)"), "{using}");
    assert_eq!(
        access(&app, &cookie, "docs").await["policies"],
        json!([]),
        "scoped to avatars"
    );

    assert_eq!(
        upload(&app, &ana_token, &format!("avatars/{ana}/me.txt")).await,
        StatusCode::CREATED
    );
    let other = Uuid::new_v4();
    assert_ne!(
        upload(&app, &ana_token, &format!("avatars/{other}/x.txt")).await,
        StatusCode::CREATED
    );

    // A policy that names no bucket covers every bucket.
    app.admin_client
        .batch_execute(
            "CREATE POLICY everyone_reads ON storage.objects FOR SELECT TO anon USING (true)",
        )
        .await
        .unwrap();
    let docs = access(&app, &cookie, "docs").await;
    assert_eq!(docs["policies"][0]["name"], "everyone_reads");
    assert_eq!(docs["policies"][0]["all_buckets"], true);

    // Recorded for "Generate migration", then dropped.
    let changes: i64 = app
        .admin_client
        .query_one(
            "SELECT count(*) FROM nelcota.panel_changes WHERE target = 'avatars_own_folder'",
            &[],
        )
        .await
        .unwrap()
        .get(0);
    assert_eq!(changes, 1);
    let dropped = send(
        &app,
        Method::DELETE,
        "/admin/api/storage/buckets/avatars/access/avatars_own_folder",
        &cookie,
        json!(null),
    )
    .await;
    assert_eq!(dropped.status, StatusCode::OK, "{}", dropped.text);
    let left: Vec<Value> = access(&app, &cookie, "avatars").await["policies"]
        .as_array()
        .unwrap()
        .clone();
    assert_eq!(left.len(), 1, "only the all-buckets policy is left");

    let missing = send(
        &app,
        Method::POST,
        "/admin/api/storage/buckets/nope/access",
        &cookie,
        json!({ "template": "public_read" }),
    )
    .await;
    assert_eq!(missing.status, StatusCode::NOT_FOUND);
}

#[tokio::test]
async fn refused_api_requests_are_listed_for_the_panel() {
    let app = TestApp::spawn().await;
    let cookie = login(&app).await;
    let (ana, ana_token) = signed_up(&app, "ana@example.com").await;

    // Allowed requests and the panel's own routes are not recorded.
    assert_eq!(app.get("/rest/v1/products", None).await.0, StatusCode::OK);
    assert_eq!(
        get(&app, "/admin/api/denied", &cookie).await.body["requests"],
        json!([])
    );

    // A visitor without a GRANT, a write RLS refuses, and a bad token.
    assert_eq!(
        app.get("/rest/v1/todos?title=eq.secret", None).await.0,
        StatusCode::UNAUTHORIZED
    );
    let other = Uuid::new_v4();
    let refused = app
        .post(
            "/rest/v1/todos",
            Some(&ana_token),
            json!({ "title": "not mine", "user_id": other }),
        )
        .await;
    assert_eq!(refused.status, StatusCode::FORBIDDEN, "{}", refused.text);
    assert_eq!(
        app.get("/rest/v1/todos", Some("not-a-jwt")).await.0,
        StatusCode::UNAUTHORIZED
    );

    let reply = get(&app, "/admin/api/denied", &cookie).await;
    assert_eq!(reply.status, StatusCode::OK, "{}", reply.text);
    let requests = reply.body["requests"].as_array().unwrap();
    assert_eq!(requests.len(), 3, "{requests:?}");
    // Newest first.
    assert_eq!(requests[0]["role"], "invalid_token");
    assert_eq!(requests[0]["code"], "invalid_token");

    let write = &requests[1];
    assert_eq!(write["method"], "POST");
    assert_eq!(write["path"], "/rest/v1/todos");
    assert_eq!(write["status"], 403);
    assert_eq!(write["role"], "authenticated");
    assert_eq!(write["user_id"], ana.to_string());
    assert!(
        write["message"]
            .as_str()
            .unwrap()
            .contains("row-level security"),
        "{write}"
    );

    let read = &requests[2];
    assert_eq!(read["role"], "anon");
    assert_eq!(read["status"], 401);
    assert_eq!(read["code"], "db_error");
    assert_eq!(
        read["path"], "/rest/v1/todos",
        "the query string is never kept"
    );
    assert!(read["at"].as_str().unwrap().ends_with('Z'));
    assert_eq!(reply.body["capacity"], 100);
}

#[tokio::test]
async fn api_traffic_is_counted_per_minute_for_the_overview() {
    let app = TestApp::spawn().await;
    let cookie = login(&app).await;
    assert_eq!(app.get("/rest/v1/products", None).await.0, StatusCode::OK);
    assert_eq!(
        app.get("/rest/v1/todos", None).await.0,
        StatusCode::UNAUTHORIZED
    );
    // The panel's own routes and /health are not API traffic.
    get(&app, "/admin/api/overview", &cookie).await;
    app.get("/health", None).await;

    let reply = get(&app, "/admin/api/metrics?range=1h", &cookie).await;
    assert_eq!(reply.status, StatusCode::OK, "{}", reply.text);
    assert_eq!(reply.body["range"], "1h");
    assert_eq!(reply.body["step_secs"], 60);
    assert_eq!(reply.body["points"].as_array().unwrap().len(), 60);
    let totals = &reply.body["totals"];
    assert_eq!(totals["requests"], 2);
    assert_eq!(totals["refused"], 1);
    assert_eq!(totals["rest"], 2);
    assert!(totals["p95_ms"].is_number());
    let last = reply.body["points"].as_array().unwrap().last().unwrap();
    assert!(last["requests"].as_u64().unwrap() >= 1, "{last}");

    let day = get(&app, "/admin/api/metrics", &cookie).await;
    assert_eq!(day.body["range"], "24h");
    assert_eq!(day.body["points"].as_array().unwrap().len(), 96);
    assert_eq!(
        get(&app, "/admin/api/metrics?range=7d", &cookie)
            .await
            .status,
        StatusCode::BAD_REQUEST
    );
}
