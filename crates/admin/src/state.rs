//! Dependencies shared by the panel workflows.
use crate::{
    Credentials, DeniedLog, ExportExecutor, HostLink, Metrics, Sessions, SqlExecutor, TokenIssuer,
};
use deadpool_postgres::Pool;
use nelcota_api::CatalogHandle;
use nelcota_auth::{Passwords, RateLimiter};
use std::sync::Arc;
#[derive(Clone)]
pub struct AdminState {
    /// Server-owned egress policy, also used by the background worker.
    pub webhooks: nelcota_webhooks::destination::Policy,
    /// Bounded SQL executions shared by all panel sessions.
    pub sql: Arc<SqlExecutor>,
    /// Dedicated, bounded export connections; slow downloads never hold `db`.
    pub exports: Arc<ExportExecutor>,
    /// Admin pool (role that owns the schema).
    pub db: Pool,
    /// Admin config, for dedicated SQL editor and export connections.
    pub db_config: tokio_postgres::Config,
    pub catalog: Arc<CatalogHandle>,
    pub credentials: Arc<Credentials>,
    pub sessions: Arc<Sessions>,
    pub limiter: Arc<RateLimiter>,
    /// Shared process-wide Argon2 budget, also used by public authentication.
    pub passwords: Arc<Passwords>,
    pub trust_proxy: bool,
    /// Cookie with `Secure` (behind Caddy/HTTPS).
    pub secure_cookies: bool,
    /// Current project, the host's project list and single sign-on.
    pub host: Arc<HostLink>,
    /// service_role token issuing from the API page.
    pub tokens: Arc<TokenIssuer>,
    /// The project's `migrations/` folder, when reachable (so migrations
    /// generated by the panel never collide with unapplied files).
    pub migrations_dir: Option<std::path::PathBuf>,
    pub production: bool,
    /// File storage, when a backend is configured.
    pub storage: Option<nelcota_storage::StorageState>,
    /// How the app's users can sign in (from the environment, read-only).
    pub sign_in: Arc<crate::contracts::SignIn>,
    /// API requests refused recently; the server records into it.
    pub denied: Arc<DeniedLog>,
    /// API traffic per minute (last 24 h); the server records into it.
    pub metrics: Arc<Metrics>,
}
