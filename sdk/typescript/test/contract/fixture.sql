-- Schema the SDK contract tests run against (scripts/contract.ts applies it).

CREATE TYPE public.order_status AS ENUM ('open', 'paid', 'shipped');

CREATE TABLE public.customers (
    id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL
);

CREATE TABLE public.orders (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner       uuid NOT NULL DEFAULT auth.uid(),
    customer_id bigint REFERENCES public.customers (id),
    status      public.order_status NOT NULL DEFAULT 'open',
    total       numeric(10,2) NOT NULL DEFAULT 0,
    note        text
);

CREATE TABLE public.items (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL REFERENCES public.orders (id) ON DELETE CASCADE,
    product  text NOT NULL,
    qty      integer NOT NULL DEFAULT 1
);
CREATE INDEX ON public.items (order_id);

-- Free text values for the encoder round trip.
CREATE TABLE public.echo (
    id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner uuid NOT NULL DEFAULT auth.uid(),
    value text NOT NULL,
    slug  text UNIQUE
);

-- Exact numeric and nullable array-element regression fixtures.
CREATE TABLE public.measurements (
    id bigint PRIMARY KEY,
    amount numeric NOT NULL,
    tags text[] NOT NULL,
    states public.order_status[] NOT NULL
);
